class TestBuild:
    def test_training_packets_are_the_protocol_tables(self, built):
        for tid, rows in TABLE_ROWS.items():
            text = (built / "training" / f"{tid}.md").read_text(encoding="utf-8")
            assert text.startswith(f"# Training packet {tid} (")
            assert "Item I01: P = 4 cards, R = 3 slots; the tray is zone 0 (`dragzone`)." in text
            assert _table_rows(text) == rows, tid

    def test_packet_titles_name_no_code(self, built):
        """The heading is what a blind reader sees: no anomaly code in it."""
        for r in _read_csv(built / "training" / "packets.csv"):
            heading = (built / "training" / f"{r['training_id']}.md").read_text(encoding="utf-8").splitlines()[0]
            for code in ("MALFORMED", "OFFBOARD", "NOOP", "DUP", "TIE", "GAP", "OTHER"):
                assert code not in heading.upper().replace("TRAINING", ""), (r["training_id"], heading)

    def test_training_packets_are_the_drawn_packets(self, built):
        packets = {r["training_id"]: r for r in _read_csv(built / "training" / "packets.csv")}
        assert {t: r["fixture"] for t, r in packets.items()} == FIXTURE_OF
        assert {t: {int(x) for x in r["rows_in_notes"].split()} for t, r in packets.items()} == ROWS_IN_NOTES
        for tid, row in packets.items():
            drawn = (built / "draw" / "packets" / f"{row['audit_id']}.md").read_text(encoding="utf-8")
            training = (built / "training" / f"{tid}.md").read_text(encoding="utf-8")
            # Only the heading differs: the body is the live packet format.
            assert training.split("\n", 1)[1] == drawn.split("\n", 1)[1]

    def test_expected_sheet_is_the_protocol_answers(self, built, expected_rows, kit):
        kit_rows_named = kit.rows_named
        packets = {r["training_id"]: r["audit_id"] for r in _read_csv(built / "training" / "packets.csv")}
        assert [(r["audit_id"], r["row_no"], r["state"], r["anomalies"]) for r in expected_rows] == [
            (packets[tid], row, state, codes) for tid, row, state, codes in EXPECTED
        ]
        assert all(r["judgment"] == "" and r["minutes"] == "" for r in expected_rows)
        # The canonical note sits on the final row of each packet that carries
        # codes and names exactly the rows the codes refer to (§6: the packet
        # row numbers in notes); every other note is blank.
        notes = {(r["audit_id"], r["row_no"]): r["notes"] for r in expected_rows}
        final_notes = {packets[tid]: rows for tid, rows in ROWS_IN_NOTES.items()}
        for (aid, row_no), note in notes.items():
            if row_no == "final" and final_notes[aid]:
                assert kit_rows_named(note) == final_notes[aid], aid
            else:
                assert note == "", (aid, row_no)
        template = _read_csv(built / "training" / "sheet_template.csv")
        assert [(r["audit_id"], r["row_no"], r["target"]) for r in template] == [
            (r["audit_id"], r["row_no"], r["target"]) for r in expected_rows
        ]
        assert all(r["state"] == "" and r["anomalies"] == "" for r in template)

    def test_expected_states_are_the_pipelines_stored_states(self, built, expected_rows, kit):
        sealed = {(r["audit_id"], r["row_no"]): r for r in _read_csv(built / "draw" / "sealed" / "checks.csv")}
        for r in expected_rows:
            stored = kit.audit_sample.parse_state(sealed[(r["audit_id"], r["row_no"])]["replayed_state"])
            assert kit.audit_sample.parse_state(r["state"]) == stored, (r["audit_id"], r["row_no"])

    def test_every_fixture_attempt_is_drawn_whole(self, built):
        manifest = json.loads((built / "draw" / "sealed" / "draw_manifest.json").read_text())
        assert manifest["sample"] == manifest["population"]
        assert sum(manifest["population"].values()) == 5
        # Kit v1.1: the two supplement attempts carry warning flags only, so
        # they are the `limited` stratum and double-reviewed.
        assert manifest["population"]["limited"] == 2 and manifest["double_review"] == 4
        assert manifest["seed"] == 20260907
        assert manifest["reconstruct_config"]["question_id"] is None

    def test_regeneration_matches_the_committed_kit(self, built):
        """The committed kit is what a fresh build writes (the manifest's
        path, hash and timestamp aside): the §11 packets as the pipeline
        replays the frozen fixtures today."""
        def listing(root: Path) -> dict[str, Path]:
            return {
                str(p.relative_to(root)): p
                for sub in ("draw", "training")
                for p in (root / sub).rglob("*")
                if p.is_file() and p.name not in SCORER_OUTPUTS
            }
        committed, fresh = listing(COMMITTED), listing(built)
        assert set(committed) == set(fresh)
        for rel, path in committed.items():
            if rel.endswith("draw_manifest.json"):
                a = json.loads(path.read_text(encoding="utf-8"))
                b = json.loads(fresh[rel].read_text(encoding="utf-8"))
                for volatile in ("db", "db_sha256", "drawn_at"):
                    a.pop(volatile), b.pop(volatile)
                assert a == b
            else:
                assert path.read_bytes() == fresh[rel].read_bytes(), rel

    def test_the_fixture_database_is_not_committable(self):
        ignore = (COMMITTED / ".gitignore").read_text(encoding="utf-8").splitlines()
        assert "fixture.sqlite" in ignore
        assert {"draw/audit-results.md", "draw/disagreements.csv"} <= set(ignore)


class TestCheck:
    def test_accepts_the_expected_sheet(self, kit, built, capsys):
        assert _check(kit, built, built / "training" / "expected_sheet.csv", "--no-score") == 0
        out = capsys.readouterr().out
        assert "B: PASS" in out and "12 targets" in out

    def test_runs_the_protocol_scorer(self, kit, built, capsys):
        assert _check(kit, built, built / "training" / "expected_sheet.csv") == 0
        assert "# Manual-audit scoring" in capsys.readouterr().out
        assert (built / "draw" / "audit-results.md").exists()
        # A sheet that reproduces §11 agrees with the pipeline on every target.
        assert _read_csv(built / "draw" / "disagreements.csv") == []

    @pytest.mark.parametrize(
        "mutate, message",
        [
            (lambda rows: rows[0].__setitem__("state", "1,2,3,3"),
             "A001 row 5: state 1,2,3,3 differs from the expected 1,2,2,3"),
            (lambda rows: rows[3].__setitem__("state", ""),
             "row 1: state blank or unreadable"),
            (lambda rows: rows[5].__setitem__("anomalies", "MALFORMED"),
             "anomaly codes ['MALFORMED'] differ from the expected ['MALFORMED', 'OFFBOARD']"),
            (lambda rows: rows[0].__setitem__("anomalies", "GAP"),
             "anomaly codes ['GAP'] differ from the expected (none)"),
            (lambda rows: rows.pop(2),
             "A001 row final: missing from the sheet"),
            (lambda rows: rows[5].__setitem__("notes", "card 9 and slot 7 do not exist on a 4-card, 3-slot board"),
             "A003: the notes must name packet rows [3, 4]"),
            (lambda rows: rows[5].__setitem__("notes", "row 4 OFFBOARD only"),
             "named: [4]"),
            (lambda rows: rows.append({"audit_id": "A003", "row_no": "3", "target": "check",
                                       "state": "0,0,0,0", "anomalies": "", "judgment": "",
                                       "notes": "", "minutes": ""}),
             "rows the training template does not have (the sheet must hold exactly its rows; "
             "brief Part 3): A003 row 3"),
            # Kit v1.1: T3 (rows 6-8) and T4 (rows 9-11) each miss one code.
            (lambda rows: rows[8].__setitem__("anomalies", "NOOP"),
             "anomaly codes ['NOOP'] differ from the expected ['GAP', 'NOOP']"),
            (lambda rows: rows[11].__setitem__("anomalies", "DUP;NOOP"),
             "anomaly codes ['DUP', 'NOOP'] differ from the expected ['DUP', 'NOOP', 'TIE']"),
            (lambda rows: rows[8].__setitem__("notes", "a no-op and a long pause"),
             "the notes must name packet rows [3, 6]"),
            # A time annotation with a spaced dash is not a row range: "row 3 - 10
            # seconds" names row 3 only, so row 4 is still missing (PR #232 review).
            (lambda rows: rows[11].__setitem__("notes", "row 2 - 0 seconds: DUP and NOOP; row 3 - 10 seconds: TIE"),
             "the notes must name packet rows [2, 3, 4]"),
        ],
        ids=["wrong-state", "blank-state", "missing-code", "spurious-code", "missing-target",
             "codes-without-rows", "one-row-missing", "extra-row",
             "missing-gap", "missing-tie", "t3-codes-without-rows", "time-annotations-are-not-ranges"],
    )
    def test_rejects_a_sheet_that_differs(self, kit, built, expected_rows, tmp_path, capsys, mutate, message):
        rows = [dict(r) for r in expected_rows]
        mutate(rows)
        sheet = tmp_path / "sheet.csv"
        _write_csv(sheet, rows, kit.audit_sample.SHEET_COLUMNS)
        assert _check(kit, built, sheet, "--no-score") == 1
        out = capsys.readouterr().out
        assert "B: FAIL" in out and message in out and "§8" in out

    def test_refuses_a_duplicated_target_row(self, kit, built, expected_rows, tmp_path, capsys):
        """Owner entry O-146, option (a) (2026-10-15): a second row for a target
        the template has is refused by the sheet reader itself — one line per
        duplicated key, exit status 2 — for `check` and the live scorer alike,
        instead of silently replacing the first row before the comparison."""
        rows = [dict(r) for r in expected_rows]
        rows.insert(1, {**rows[0], "state": "1,2,3,3"})  # A001 row 5 twice, different states
        sheet = tmp_path / "sheet.csv"
        _write_csv(sheet, rows, kit.audit_sample.SHEET_COLUMNS)
        with pytest.raises(SystemExit) as exc:
            _check(kit, built, sheet, "--no-score")
        assert exc.value.code not in (0, None)
        err = capsys.readouterr().err
        assert ("target A001 row 5 appears 2 times; a sheet holds exactly the template's rows, "
                "one per target (handbook §3)") in err

    def test_an_added_row_supplies_neither_codes_nor_row_references(self, kit, built, expected_rows, tmp_path, capsys):
        """Brief Part 3: do not add rows. An extra row carrying the codes
        and the row references leaves the real final row empty-handed."""
        rows = [dict(r) for r in expected_rows]
        rows[5]["anomalies"], rows[5]["notes"] = "", ""
        rows.append({"audit_id": "A003", "row_no": "3", "target": "check", "state": "0,0,0,0",
                     "anomalies": "MALFORMED;OFFBOARD", "judgment": "", "notes": "row 3; row 4",
                     "minutes": ""})
        sheet = tmp_path / "sheet.csv"
        _write_csv(sheet, rows, kit.audit_sample.SHEET_COLUMNS)
        assert _check(kit, built, sheet, "--no-score") == 1
        out = capsys.readouterr().out
        assert "rows the training template does not have" in out
        assert "anomaly codes (none) differ from the expected ['MALFORMED', 'OFFBOARD']" in out
        assert "the notes must name packet rows [3, 4]" in out

    def test_judgment_minutes_and_free_notes_are_not_scored(self, kit, built, expected_rows, tmp_path):
        rows = [dict(r) for r in expected_rows]
        rows[3]["judgment"], rows[3]["notes"] = "1", "a check before any move (rows 1 and 2)"
        rows[2]["minutes"], rows[2]["notes"] = "7", "row 6 took two tries to read"
        sheet = tmp_path / "sheet.csv"
        _write_csv(sheet, rows, kit.audit_sample.SHEET_COLUMNS)
        assert _check(kit, built, sheet, "--no-score") == 0

    @pytest.mark.parametrize(
        "note", ["rows 3 and 4", "row 3; row 4", "Row 3 MALFORMED, row 4 OFFBOARD", "rows 3, 4 (card 9, slot 7)",
                 "rows 3-4", "rows 3–4 (MALFORMED, OFFBOARD)", "rows 3 to 4"],
    )
    def test_row_references_can_be_written_several_ways(self, kit, built, expected_rows, tmp_path, note):
        rows = [dict(r) for r in expected_rows]
        rows[5]["notes"] = note
        sheet = tmp_path / "sheet.csv"
        _write_csv(sheet, rows, kit.audit_sample.SHEET_COLUMNS)
        assert _check(kit, built, sheet, "--no-score") == 0

    def test_a_range_is_a_closed_up_dash_or_the_word_form(self, kit):
        """A spaced dash is a separator, not a range (PR #232 review): a time
        annotation never credits the rows between its numbers, a descending
        pair names its two rows only, and the documented forms still expand."""
        assert kit.rows_named("row 3 - 10 s: TIE") == {3}
        assert kit.rows_named("row 2 - 0 seconds: DUP and NOOP; row 3 - 10 seconds: TIE") == {2, 3}
        assert kit.rows_named("rows 4-3") == {3, 4}
        assert kit.rows_named("rows 3-4") == kit.rows_named("rows 3–4") == kit.rows_named("rows 3 to 4") == {3, 4}

    def test_row_references_are_read_across_the_attempts_rows(self, kit, built, expected_rows, tmp_path):
        rows = [dict(r) for r in expected_rows]
        rows[5]["notes"], rows[3]["notes"] = "", "row 3 could not be read; row 4 names card 9 and slot 7"
        sheet = tmp_path / "sheet.csv"
        _write_csv(sheet, rows, kit.audit_sample.SHEET_COLUMNS)
        assert _check(kit, built, sheet, "--no-score") == 0

    def test_codes_are_read_across_the_attempts_rows(self, kit, built, expected_rows, tmp_path):
        """§6 puts the codes on the final row; the scorer reads the
        attempt's code set across its rows, and so does the check."""
        rows = [dict(r) for r in expected_rows]
        rows[5]["anomalies"], rows[3]["anomalies"] = "", "MALFORMED; OFFBOARD"
        sheet = tmp_path / "sheet.csv"
        _write_csv(sheet, rows, kit.audit_sample.SHEET_COLUMNS)
        assert _check(kit, built, sheet, "--no-score") == 0
