"""
The manual audit's training kit (``proteus.paper1.audit_training_kit``, the
``proteus-audit-kit`` command; ``docs/dnd/scripts/audit_training_kit.py`` until
2026-10-27, when the kit itself moved to ``paper1/audit-training-kit/`` at the
repository root — ``cc-task-public-export`` PR 2, rulings R1 (a) and R2 (a)).

Protocol §11 (``paper1-manual-audit-protocol.md``, frozen 2026-09-27): the two
training packets are generated by ``audit_sample.py draw`` from a database
built from the regression fixtures only, and their expected answers are the
pipeline's stored states, verified against the fixture tests. These tests are
that verification: a fresh build reproduces the committed kit under
``paper1-audit-training-kit/`` byte for byte (the draw manifest's path, hash
and timestamp aside), the training packets are §11's tables, the expected
sheet is §11's answers, and ``check`` accepts exactly a sheet that reproduces
them (§8's acceptance rule).

Protocol §11 names T1 and T2; the protocol's 2026-10-15 "Training supplement"
§12 line adds T3 and T4 (kit v1.1), drawn from
``golden_dnd_training_anomalies.tab`` and pinned as a regression fixture by
``test_dnd_training_anomalies.py``. Their expected answers are the §6 rules'
answers, typed from a hand replay; ``build`` refuses if the pipeline's stored
states or observable flags disagree.

Never "update" the committed kit to make these pass. A difference means the
replay of a frozen fixture changed (the DnD golden rule of CLAUDE.md) or that
§11 or the supplement was amended — and an amendment is a dated §12 entry
first, after which the script rebuilds the kit.
"""

