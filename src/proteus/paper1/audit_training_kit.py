def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)

    b = sub.add_parser("build", help="build the fixture database, draw it, write training/")
    b.add_argument("--out", type=Path, required=True, help="the kit folder")
    b.add_argument("--seed", type=int, default=20260907, help="the protocol's draw seed")
    b.set_defaults(func=cmd_build)

    c = sub.add_parser("check", help="check completed training sheets against protocol §11")
    c.add_argument("--out", type=Path, required=True, help="the kit folder a build wrote")
    c.add_argument("--sheet", action="append", default=[], metavar="NAME=PATH")
    c.add_argument("--no-score", action="store_true",
                   help="skip the protocol's scorer (audit_sample.py score) after the comparison")
    c.set_defaults(func=cmd_check)

    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
