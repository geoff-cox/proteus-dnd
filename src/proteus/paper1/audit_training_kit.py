def build_fixture_db(path: Path) -> None:
    """The fixture-only database, every DnD stage run under the primary
    configuration (the stage defaults), boards synced from the fixture
    item source through the real sync path."""
    if path.exists():
        path.unlink()
    conn = db.connect(path)
    try:
        db.bootstrap(conn)
        textbook_id = conn.execute(
            "INSERT INTO textbooks (git_repo_url, git_ref, book_xml_id, build_dir) "
            "VALUES ('fixture', 'fixture', 'demo-book', 'fixture')"
        ).lastrowid
        with tempfile.TemporaryDirectory() as tmp:
            src = Path(tmp) / "src"
            src.mkdir()
            shutil.copy(ITEM_SOURCE, src / ITEM_SOURCE.name)
            sources.sync_question_sources(
                conn, src, textbook_id=textbook_id, output_dir=Path(tmp) / "cache"
            )
        for name in FIXTURE_FILES:
            core_ingest.ingest_file(conn, FIXTURES / name)
        derive_events(conn)
        reconstruct_all(conn)
        score_checks(conn)
        process.analyze_all(conn)
        conn.commit()
    finally:
        conn.close()


def _read_csv(path: Path) -> list[dict]:
    with open(path, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def _codes_for_observable_flags(flags: str) -> set[str]:
    return {audit_sample.ANOMALY_FOR_FLAG[f] for f in flags.split() if f in audit_sample.ANOMALY_FOR_FLAG}


def write_training(draw: Path, training: Path) -> list[dict]:
    """``training/`` from the draw: the training packets as drawn, the
    trainee's sheet template, the expected sheet; every typed answer (§11's
    for T1 and T2, the §6 rules' for T3 and T4) checked against the sealed
    key on the way."""
    key = {r["student_id"]: r for r in _read_csv(draw / "sealed" / "sample_key.csv")}
    sealed = {
        (r["audit_id"], r["row_no"]): r for r in _read_csv(draw / "sealed" / "checks.csv")
    }
    template = _read_csv(draw / "sheet_A_template.csv")

    if training.exists():
        shutil.rmtree(training)
    training.mkdir(parents=True)
    packets_rows, template_rows, expected_rows = [], [], []
    for t in TRAINING:
        entry = key.get(t["student_id"])
        if entry is None:
            die(f"{t['training_id']}: no drawn attempt for fixture student {t['student_id']!r}")
        aid = entry["audit_id"]
        packets_rows.append({
            "training_id": t["training_id"], "audit_id": aid,
            "fixture": t["fixture"], "student_id": t["student_id"], "title": t["title"],
            "rows_in_notes": " ".join(str(r) for r in t["rows_in_notes"]),
        })
        if set(t["rows_in_notes"]) - set(range(1, int(entry["n_rows"]) + 1)):
            die(f"{t['training_id']} ({aid}): rows_in_notes {t['rows_in_notes']} are not all "
                f"packet rows (the packet has {entry['n_rows']})")
        if set(t["rows_in_notes"]) != rows_named(t["notes"]):
            die(f"{t['training_id']}: the canonical note names rows {sorted(rows_named(t['notes']))}, "
                f"not rows_in_notes {t['rows_in_notes']}")
        text = (draw / "packets" / f"{aid}.md").read_text(encoding="utf-8")
        head = f"# Audit packet {aid}"
        if not text.startswith(head):
            die(f"{aid}.md does not start with {head!r}")
        text = (f"# Training packet {t['training_id']} ({t['title']}; audit packet {aid})"
                + text[len(head):])
        (training / f"{t['training_id']}.md").write_text(text, encoding="utf-8")

        rows = [r for r in template if r["audit_id"] == aid]
        targets = {r["row_no"] for r in rows}
        if targets != set(t["expected"]):
            die(f"{t['training_id']} ({aid}): the draw's targets {sorted(targets)} are not "
                f"the typed ones {sorted(t['expected'])}")
        for r in rows:
            state, codes = t["expected"][r["row_no"]]
            stored = audit_sample.parse_state(sealed[(aid, r["row_no"])]["replayed_state"])
            if audit_sample.parse_state(state) != stored:
                die(f"{t['training_id']} ({aid}) row {r['row_no']}: the typed expected state is "
                    f"{state} but the pipeline stored {stored}; the rules' answer and the pipeline "
                    "disagree — a finding for the owner (rule gap or pipeline error), never a retype")
            template_rows.append(dict(r))
            expected_rows.append({**r, "state": state, "anomalies": codes,
                                  "notes": t["notes"] if r["row_no"] == "final" else ""})
        observable = _codes_for_observable_flags(entry["observable_flags"])
        expected_codes = audit_sample.parse_codes(t["expected"]["final"][1])
        if observable != expected_codes:
            die(f"{t['training_id']} ({aid}): the typed expected codes are {sorted(expected_codes)} "
                f"but the draw records observable flags for {sorted(observable)}")

    audit_sample.write_csv(training / "packets.csv", packets_rows, PACKETS_COLUMNS)
    audit_sample.write_csv(training / "sheet_template.csv", template_rows, audit_sample.SHEET_COLUMNS)
    audit_sample.write_csv(training / "expected_sheet.csv", expected_rows, audit_sample.SHEET_COLUMNS)
    return packets_rows


def cmd_build(args) -> int:
    out: Path = args.out
    out.mkdir(parents=True, exist_ok=True)
    db_path = out / "fixture.sqlite"
    build_fixture_db(db_path)
    draw = out / "draw"
    if draw.exists():
        shutil.rmtree(draw)
    audit_sample.cmd_draw(argparse.Namespace(
        db=db_path, out=draw, seed=args.seed, n_agree=80, cap_mismatch=60,
        cap_excluded=40, cap_limited=40, double_agree_frac=0.25,
        offering_map=None, allow_nonprimary=False, allow_anywhere=True,
    ))
    packets = write_training(draw, out / "training")
    for p in packets:
        print(f"{p['training_id']} = audit packet {p['audit_id']} ({p['title']}; "
              f"{p['fixture']}, {p['student_id']})")
    print(f"training kit v{KIT_VERSION} written under {out}")
    return 0


