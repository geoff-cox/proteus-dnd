"""Paper 1 manual audit: the reviewers' training kit (protocol §8 and §11).

Companion to ``paper1-manual-audit-protocol.md`` (v1.0, frozen 2026-09-27)
and to ``audit_sample.py``. The protocol's §11 says the two training packets
are generated by ``audit_sample.py draw`` from a database built from the
regression fixtures only; this script is that build, so a trainee works on
packets in exactly the live format, and §8's acceptance rule — both
reviewers reproduce the expected answers exactly, codes included, before the
live sample is opened — is checked mechanically rather than by eye.

No student data is involved: the fixtures are the hand-made
``golden_dnd_worked_example.tab`` (T1, the six-move worked example),
``golden_dnd.tab`` (T2, the pathological attempt) and, since kit v1.1 (the
protocol's 2026-10-15 "Training supplement" §12 line),
``golden_dnd_training_anomalies.tab`` (T3, a no-op drop and a long gap with a
reset on the way; T4, a repeated drop and a drop/CHECK tie), so the kit may be
committed and shared freely (protocol §10 and §11). The draw's
``data/private`` guard is lifted here for that reason only. A packet's title
never names the codes it exercises: the heading is what a blind reader sees.

Two subcommands::

    proteus-audit-kit build \
        --out paper1/audit-training-kit
    proteus-audit-kit check \
        --out paper1/audit-training-kit \
        --sheet B=/path/to/the/trainee's/sheet.csv

``build`` writes, under ``--out``:

``fixture.sqlite``
    the fixture-only database (boards synced from the fixture item source
    through the real sync path; the three fixtures ingested, derived,
    reconstructed, scored and analyzed under the primary configuration).
    Rebuilt on every ``build``; never committed (the folder's .gitignore).
``draw/``
    ``audit_sample.py draw`` on that database, as is: ``packets/``,
    ``packets-all.md``, the two sheet templates and ``sealed/``. Every
    fixture attempt is drawn (five since kit v1.1; the strata are taken
    whole), so the folder also holds one packet that no training packet
    names — the reference trace of ``golden_dnd.tab``, an optional extra.
``training/``
    what a trainee receives: ``T1.md`` to ``T4.md`` (the §11 packets and the
    2026-10-15 supplement, as drawn), ``sheet_template.csv`` (their rows of
    the reviewer sheet) and ``packets.csv`` (which audit id each training
    packet is); and what the trainer keeps until the first pass is in:
    ``expected_sheet.csv``, the expected answers in sheet form.

``build`` refuses to finish if a typed expected answer differs from the
pipeline's stored states or from the flags the draw records as observable —
the protocol's "verified against the fixture tests" link, kept live. The
answers are the §6 rules' answers, typed from a hand replay; a refusal is a
finding for the owner (a rule gap or a pipeline error), never a reason to
retype the answer.

``check`` compares each ``--sheet NAME=PATH`` with ``expected_sheet.csv``
target by target: the sheet must hold exactly the template's rows (a row
the template does not have fails it); the state on every row; the attempt's
anomaly-code set, read across its rows as the scorer reads it; and, where
codes are expected, that the attempt's notes name the packet rows the codes
refer to (§6: "with the packet row numbers in notes"; §11's T2 names rows 3
and 4), written as ``row 3``, ``row 4`` (``rows 3 and 4`` also reads).
``judgment`` and ``minutes`` are never scored. It then runs the protocol's scorer on the
draw, so the trainer also sees §7's tables for the sheet. Exit status 1 if
any sheet differs from the expected answers or is incomplete.
"""

