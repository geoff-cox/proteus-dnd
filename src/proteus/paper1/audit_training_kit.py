def compare_sheet(sheet: dict, expected: dict,
                  rows_in_notes: dict[str, set[int]] | None = None) -> list[str]:
    """Every way a trainee's sheet differs from the expected sheet: a row
    the template does not have, a missing target, a blank or different
    state, an attempt whose anomaly codes (read across its rows, as the
    scorer reads them) differ, and an attempt whose notes do not name the
    packet rows its codes refer to (``rows_in_notes``: audit id -> the rows
    §11 expects named). Only the template's rows are read: an added row
    can neither supply codes nor row references."""
    problems: list[str] = []
    unexpected = sorted(
        set(sheet) - set(expected),
        key=lambda k: (k[0], k[1] == "final", int(k[1]) if k[1].isdigit() else 0),
    )
    if unexpected:
        problems.append(
            "rows the training template does not have (the sheet must hold exactly "
            "its rows; brief Part 3): "
            + ", ".join(f"{a or '(blank)'} row {r or '(blank)'}" for a, r in unexpected)
        )
    sheet = {k: e for k, e in sheet.items() if k in expected}
    codes_expected: dict[str, set[str]] = {}
    codes_seen: dict[str, set[str]] = {}
    for (aid, row_no), exp in expected.items():
        codes_expected.setdefault(aid, set()).update(audit_sample.parse_codes(exp["anomalies"]))
        entry = sheet.get((aid, row_no))
        if entry is None:
            problems.append(f"{aid} row {row_no}: missing from the sheet")
            continue
        codes_seen.setdefault(aid, set()).update(audit_sample.parse_codes(entry["anomalies"]))
        want = audit_sample.parse_state(exp["state"])
        got = audit_sample.parse_state(entry["state"])
        if got is None:
            problems.append(f"{aid} row {row_no}: state blank or unreadable "
                            f"({entry['state']!r}); expected {exp['state']}")
        elif got != want:
            problems.append(f"{aid} row {row_no}: state {','.join(map(str, got))} differs from "
                            f"the expected {exp['state']}")
    for aid, want in codes_expected.items():
        got = codes_seen.get(aid)
        if got is None:
            continue  # every row missing; reported above
        if got != want:
            problems.append(f"{aid}: anomaly codes {sorted(got) or '(none)'} differ from the "
                            f"expected {sorted(want) or '(none)'}")
    for aid, required in (rows_in_notes or {}).items():
        rows = [e for (a, _), e in sheet.items() if a == aid]
        if not required or not rows:
            continue  # nothing to name, or every row missing (reported above)
        named = set().union(*(rows_named(e.get("notes", "")) for e in rows))
        if not required <= named:
            problems.append(f"{aid}: the notes must name packet rows {sorted(required)} "
                            f"(§6: the packet row numbers in notes, as `row 3`, `row 4`); "
                            f"named: {sorted(named) or 'none'}")
    return problems


def cmd_check(args) -> int:
    out: Path = args.out
    expected = audit_sample.read_sheet(out / "training" / "expected_sheet.csv")
    rows_in_notes = {
        r["audit_id"]: {int(x) for x in r["rows_in_notes"].split()}
        for r in _read_csv(out / "training" / "packets.csv")
    }
    if not args.sheet:
        die("at least one --sheet NAME=PATH is required")
    sheets = {}
    for spec in args.sheet:
        name, _, path = spec.partition("=")
        if not path:
            die("--sheet takes NAME=PATH")
        sheets[name] = Path(path)
    failed = 0
    for name, path in sheets.items():
        problems = compare_sheet(audit_sample.read_sheet(path), expected, rows_in_notes)
        verdict = "PASS" if not problems else "FAIL"
        print(f"{name}: {verdict} — {len(expected)} targets of training kit v{KIT_VERSION} "
              f"({', '.join(sorted({aid for aid, _ in expected}))})")
        for p in problems:
            print(f"  - {p}")
        failed += bool(problems)
    if failed:
        print("§8: a discrepancy is a defect in §6's wording or a training gap — "
              "resolve it, then repeat the training until both sheets reproduce the "
              "expected answers exactly.")
    if not args.no_score:
        print()
        audit_sample.cmd_score(argparse.Namespace(
            db=out / "fixture.sqlite", out=out / "draw", sheet=list(args.sheet),
            allow_anywhere=True,
        ))
    return 1 if failed else 0


