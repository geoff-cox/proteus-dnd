PACKETS_COLUMNS = ("training_id", "audit_id", "fixture", "student_id", "title", "rows_in_notes")

# Packet rows named in a note: the numbers after "row" / "rows", so that
# "rows 3 and 4", "row 3; row 4", "rows 3, 4" and (since kit v1.1, whose T4
# ties an adjacent pair) "rows 3-4", "rows 3–4", "rows 3 to 4" all read as
# {3, 4}, while "a 4-card, 3-slot board" names nothing. A range is a
# closed-up dash or the word form, ascending: a spaced dash is a separator,
# so a time annotation such as "row 3 - 10 s" names row 3 only and never
# credits the rows between (PR #232 review).
_RANGE = r"(?:[-–—]|\s+(?:to|through)\s+)"
ROW_REF = re.compile(
    r"\brows?\s*#?\s*(\d+(?:(?:\s*(?:,|;|and|&|/)\s*|" + _RANGE + r")\d+)*)", re.I
)
_RANGE_PAIR = re.compile(r"(\d+)" + _RANGE + r"(\d+)", re.I)


def rows_named(notes: str) -> set[int]:
    found: set[int] = set()
    for group in ROW_REF.findall(notes or ""):
        for a, b in _RANGE_PAIR.findall(group):
            if int(a) < int(b):
                found.update(range(int(a), int(b) + 1))
        found.update(int(n) for n in re.findall(r"\d+", group))
    return found


def die(msg: str) -> None:
    print(f"error: {msg}", file=sys.stderr)
    raise SystemExit(2)


